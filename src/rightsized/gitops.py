"""Write recommendations into Git (manifests or Helm values) and open a PR.

The tool never talks to the API server to change anything; the PR is the only output.
"""

from __future__ import annotations

import io
import subprocess
from pathlib import Path

from ruamel.yaml import YAML
from ruamel.yaml.comments import CommentedMap

from .config import Config, Target
from .models import Recommendation, Resources
from .units import format_cpu, format_memory


def _yaml() -> YAML:
    y = YAML()  # round-trip: keeps comments, key order and quoting
    y.preserve_quotes = True
    y.indent(mapping=2, sequence=4, offset=2)
    y.width = 4096
    return y


def _set_block(block: CommentedMap, key: str, res: Resources) -> None:
    sub = block.get(key)
    if sub is None:
        if res.cpu is None and res.memory is None:
            return
        sub = block[key] = CommentedMap()
    if res.cpu is not None:
        sub["cpu"] = format_cpu(res.cpu)
    if res.memory is not None:
        sub["memory"] = format_memory(res.memory)


def _apply_resources(resources: CommentedMap, rec: Recommendation) -> None:
    _set_block(resources, "requests", rec.requests)
    # Only touch limits that already exist; adding limits is a policy decision, not sizing.
    if "limits" in resources:
        _set_block(resources, "limits", rec.limits)


def patch_manifest(text: str, namespace: str, workload: str, container: str, rec: Recommendation) -> str:
    y = _yaml()
    docs = list(y.load_all(text))
    found = False
    for doc in docs:
        if not isinstance(doc, dict) or doc.get("kind") not in ("Deployment", "StatefulSet", "DaemonSet"):
            continue
        meta = doc.get("metadata", {})
        if meta.get("name") != workload or meta.get("namespace", namespace) != namespace:
            continue
        for c in doc["spec"]["template"]["spec"]["containers"]:
            if c.get("name") == container:
                if "resources" not in c:
                    c["resources"] = CommentedMap()
                _apply_resources(c["resources"], rec)
                found = True
    if not found:
        raise KeyError(f"{namespace}/{workload}/{container} not found in manifest")
    buf = io.StringIO()
    y.dump_all(docs, buf)
    return buf.getvalue()


def patch_helm_values(text: str, path: str, rec: Recommendation) -> str:
    y = _yaml()
    root = y.load(text)
    node = root
    for part in path.split("."):
        if part not in node or node[part] is None:
            node[part] = CommentedMap()
        node = node[part]
    _apply_resources(node, rec)
    buf = io.StringIO()
    y.dump(root, buf)
    return buf.getvalue()


def apply_to_repo(repo: Path, recs: list[Recommendation], cfg: Config) -> tuple[list[Path], list[str]]:
    """Patch files in place. Returns (changed files, keys that had no Git target)."""
    changed: dict[Path, str] = {}
    missing: list[str] = []
    for rec in recs:
        ev = rec.evidence
        t: Target | None = cfg.target_for(ev.namespace, ev.workload, ev.container)
        if t is None:
            missing.append(rec.key)
            continue
        f = repo / t.file
        text = changed.get(f, f.read_text())
        if t.mode == "helm":
            changed[f] = patch_helm_values(text, t.path, rec)
        else:
            changed[f] = patch_manifest(text, ev.namespace, ev.workload, ev.container, rec)
    for f, text in changed.items():
        f.write_text(text)
    return sorted(changed), missing


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, text=True).stdout


def open_pr(repo: Path, files: list[Path], branch: str, title: str, body: str, base: str = "main") -> str:
    _git(repo, "checkout", "-b", branch)
    _git(repo, "add", *[str(f) for f in files])
    _git(repo, "commit", "-m", title, "-m", "Generated by rightsized. Evidence in PR description.")
    _git(repo, "push", "-u", "origin", branch)
    body_file = repo / ".git" / "RIGHTSIZED_PR_BODY.md"
    body_file.write_text(body)
    out = subprocess.run(
        ["gh", "pr", "create", "--base", base, "--head", branch, "--title", title, "--body-file", str(body_file)],
        cwd=repo, check=True, capture_output=True, text=True,
    )
    return out.stdout.strip()
